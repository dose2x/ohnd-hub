/* ---------- Tab switching ---------- */
const SCREENS = ["movies", "jokes", "wyr", "discord", "website"];
function showScreen(name) {
  SCREENS.forEach(s => {
    document.getElementById("screen-" + s).classList.toggle("active", s === name);
  });
  document.querySelectorAll(".tab-btn").forEach(btn => {
    const active = btn.dataset.screen === name;
    btn.classList.toggle("active", active);
    btn.setAttribute("aria-current", active ? "page" : "false");
  });
  document.querySelector("main").scrollTop = 0;
}
document.querySelectorAll(".tab-btn").forEach(btn => {
  btn.addEventListener("click", () => showScreen(btn.dataset.screen));
});

/* ---------- Random decks (shared by Jokes & WYR) ---------- */
// Shuffles once, then deals without repeats until every item has been shown.
function makeDeck(items) {
  let order = [];
  return () => {
    if (!order.length) {
      order = [...items.keys()];
      for (let i = order.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [order[i], order[j]] = [order[j], order[i]];
      }
    }
    return items[order.pop()];
  };
}

function pop(el) {
  el.classList.remove("pop");
  void el.offsetWidth; // restart the CSS animation
  el.classList.add("pop");
}

