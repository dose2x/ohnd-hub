const MOVIE_PROXY_URL = "https://ohnd-movie-proxy.ohndtomatometer.workers.dev";

const movieEls = {
  query: document.getElementById("movieQuery"),
  searchBtn: document.getElementById("movieSearchBtn"),
  status: document.getElementById("movieStatus"),
  card: document.getElementById("movieCard"),
  poster: document.getElementById("moviePoster"),
  title: document.getElementById("movieTitle"),
  meta: document.getElementById("movieMeta"),
  scores: document.getElementById("movieScores"),
  plot: document.getElementById("moviePlot"),
  actors: document.getElementById("movieActors"),
  director: document.getElementById("movieDirector"),
};

function setMovieStatus(msg, isError) {
  movieEls.status.textContent = msg || "";
  movieEls.status.classList.toggle("error", !!isError);
}

function ratingClass(value) {
  const num = parseInt(value, 10);
  if (isNaN(num)) return "";
  return num >= 60 ? "fresh" : "rotten";
}

// OMDb uses the string "N/A" for missing fields.
const has = (v) => Boolean(v) && v !== "N/A";

// Built with textContent (never innerHTML) so API data can't inject markup.
function scorePill(source, value, cls = "") {
  const pill = document.createElement("div");
  pill.className = "score-pill";
  const label = document.createElement("span");
  label.textContent = source;
  const val = document.createElement("span");
  val.className = `val ${cls}`.trim();
  val.textContent = value;
  pill.append(label, val);
  return pill;
}

let movieRequest = null;

async function searchMovie() {
  const title = movieEls.query.value.trim();
  if (!title) {
    setMovieStatus("Type a movie title first.", true);
    return;
  }

  // Cancel any search still in flight so a slow older response can't overwrite this one.
  if (movieRequest) movieRequest.abort();
  movieRequest = new AbortController();

  movieEls.card.classList.remove("visible");
  setMovieStatus("Searching...");

  try {
    const url = `${MOVIE_PROXY_URL}/?t=${encodeURIComponent(title)}`;
    const res = await fetch(url, { signal: movieRequest.signal });
    // A Worker/Cloudflare error page isn't JSON; treat it like any other failed lookup.
    const data = await res.json().catch(() => ({}));

    if (!res.ok || data.Response !== "True") {
      setMovieStatus(data.Error || "Movie not found.", true);
      return;
    }

    movieEls.title.textContent = has(data.Year) ? `${data.Title} (${data.Year})` : data.Title;
    movieEls.meta.textContent = [data.Rated, data.Runtime, data.Genre].filter(has).join(" • ");
    movieEls.poster.hidden = !has(data.Poster);
    if (has(data.Poster)) {
      movieEls.poster.src = data.Poster;
      movieEls.poster.alt = `${data.Title} poster`;
    }
    movieEls.plot.textContent = has(data.Plot) ? data.Plot : "No synopsis available.";
    movieEls.actors.textContent = has(data.Actors) ? data.Actors : "Not listed.";
    movieEls.director.textContent = has(data.Director) ? data.Director : "Not listed.";

    const ratings = Array.isArray(data.Ratings) ? data.Ratings : [];
    const pills = ratings.map(r =>
      scorePill(r.Source, r.Value, r.Source === "Rotten Tomatoes" ? ratingClass(r.Value) : ""));
    if (has(data.Metascore) && !ratings.some(r => r.Source === "Metacritic")) {
      pills.push(scorePill("Metascore", data.Metascore));
    }
    movieEls.scores.replaceChildren(...pills);

    setMovieStatus("");
    movieEls.card.classList.add("visible");
  } catch (err) {
    if (err.name === "AbortError") return; // superseded by a newer search
    setMovieStatus("Something went wrong. Check your connection and try again.", true);
  }
}

// OMDb poster links sometimes 404; hide the image instead of showing a broken icon.
movieEls.poster.addEventListener("error", () => { movieEls.poster.hidden = true; });

movieEls.searchBtn.addEventListener("click", searchMovie);
movieEls.query.addEventListener("keydown", (e) => {
  if (e.key === "Enter") searchMovie();
});

